    def _add_recent_block(self) -> None:
        recent_block = QFrame()
        recent_block.setObjectName("splitterSection")
        recent_block_layout = QVBoxLayout(recent_block)
        recent_block_layout.setContentsMargins(0, 0, 0, 0)
        recent_block_layout.setSpacing(6)
        recent_header = QHBoxLayout()
        recent_header.setSpacing(8)
        recent_title = QLabel("Recent")
        recent_title.setObjectName("panelTitle")
        self.refresh_recent_button = QPushButton("Refresh")
        self.refresh_recent_button.setObjectName("secondaryButton")
        self.refresh_recent_button.clicked.connect(self._refresh_recent_traces)
        recent_header.addWidget(recent_title, stretch=1)
        recent_header.addWidget(self.refresh_recent_button)
        recent_block_layout.addLayout(recent_header)

        self.recent_list = QListWidget()
        self.recent_list.setObjectName("recentList")
        self.recent_list.itemClicked.connect(self.load_recent_trace)
        self.recent_list.setMinimumHeight(70)
        recent_block_layout.addWidget(self.recent_list)
        self.list_splitter.addWidget(recent_block)

