    def _add_window_block(self) -> None:
        window_block = QFrame()
        window_block.setObjectName("splitterSection")
        window_block_layout = QVBoxLayout(window_block)
        window_block_layout.setContentsMargins(0, 0, 0, 0)
        window_block_layout.setSpacing(6)
        window_header = QHBoxLayout()
        window_header.setSpacing(8)
        window_title = QLabel("Windows")
        window_title.setObjectName("panelTitle")
        self.window_count_label = QLabel("Not refreshed")
        self.window_count_label.setObjectName("subtitle")
        self.refresh_windows_button = QPushButton("Refresh")
        self.refresh_windows_button.setObjectName("secondaryButton")
        self.refresh_windows_button.clicked.connect(self._refresh_window_list)
        window_header.addWidget(window_title)
        window_header.addWidget(self.window_count_label, stretch=1)
        window_header.addWidget(self.refresh_windows_button)
        window_block_layout.addLayout(window_header)

        self.window_table = QTableWidget(0, 5)
        self.window_table.setObjectName("windowTable")
        self.window_table.setHorizontalHeaderLabels(["HWND", "Title", "PID", "State", "Exe"])
        self.window_table.verticalHeader().setVisible(False)
        self.window_table.setEditTriggers(QTableWidget.EditTrigger.NoEditTriggers)
        self.window_table.setSelectionBehavior(QTableWidget.SelectionBehavior.SelectRows)
        self.window_table.setSelectionMode(QTableWidget.SelectionMode.SingleSelection)
        self.window_table.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.ResizeToContents)
        self.window_table.horizontalHeader().setSectionResizeMode(1, QHeaderView.ResizeMode.Stretch)
        self.window_table.horizontalHeader().setSectionResizeMode(2, QHeaderView.ResizeMode.ResizeToContents)
        self.window_table.horizontalHeader().setSectionResizeMode(3, QHeaderView.ResizeMode.ResizeToContents)
        self.window_table.horizontalHeader().setSectionResizeMode(4, QHeaderView.ResizeMode.Stretch)
        self.window_table.setMinimumHeight(90)
        self.window_table.itemSelectionChanged.connect(self.load_selected_window_detail)
        window_block_layout.addWidget(self.window_table)

        window_actions = QHBoxLayout()
        window_actions.setSpacing(6)
        self.focus_window_button = QPushButton("Focus")
        self.focus_window_button.setObjectName("secondaryButton")
        self.focus_window_button.clicked.connect(lambda: self._run_window_action(ActionType.FOCUS_WINDOW))
        self.minimize_window_button = QPushButton("Min")
        self.minimize_window_button.setObjectName("secondaryButton")
        self.minimize_window_button.clicked.connect(lambda: self._run_window_action(ActionType.MINIMIZE_WINDOW))
        self.restore_window_button = QPushButton("Restore")
        self.restore_window_button.setObjectName("secondaryButton")
        self.restore_window_button.clicked.connect(lambda: self._run_window_action(ActionType.RESTORE_WINDOW))
        self.maximize_window_button = QPushButton("Max")
        self.maximize_window_button.setObjectName("secondaryButton")
        self.maximize_window_button.clicked.connect(lambda: self._run_window_action(ActionType.MAXIMIZE_WINDOW))
        self.close_window_button = QPushButton("Close")
        self.close_window_button.setObjectName("dangerButton")
        self.close_window_button.clicked.connect(lambda: self._run_window_action(ActionType.CLOSE_WINDOW))
        window_actions.addWidget(self.focus_window_button)
        window_actions.addWidget(self.minimize_window_button)
        window_actions.addWidget(self.restore_window_button)
        window_actions.addWidget(self.maximize_window_button)
        window_actions.addWidget(self.close_window_button)
        window_block_layout.addLayout(window_actions)
        self._set_window_action_buttons(False)
        self.list_splitter.addWidget(window_block)

